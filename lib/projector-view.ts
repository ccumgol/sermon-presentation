/**
 * 프로젝터 화면(`/projector`)이 쓰는 템플릿.
 *
 * ## 왜 따로 두는가
 *
 * OBS 로 나가는 화면과 **동시에 다른 배치**를 써야 한다. 카메라 영상 위에 얹는
 * OBS 화면은 '하단 두 줄'이 맞지만, 프로젝터에는 전체화면 큰 글씨가 맞다.
 * 하나의 활성 템플릿을 모두에게 보내면 둘 중 하나가 망가진다.
 *
 * 그래서 서버는 `projector` layer 에만 이 템플릿을 보낸다.
 *
 * ## 바탕은 '전체 — 성경·찬송 겸용'
 *
 * 사용자가 지정한 프리셋이다. **사용자가 그 템플릿을 고치면 프로젝터도 따라간다** —
 * 별도의 숨은 설정을 만들지 않는다. 눈에 보이는 곳에서 고칠 수 있어야 한다.
 *
 * ## 색·배경·글자 크기 배수는 여기서 정하지 않는다
 *
 * 반전·줌·배경 억제는 **화면 쪽(projector.css)** 이 CSS 변수로 한다. 서버가 보내는
 * `style:patch` 는 `<html>` 인라인에 꽂히고, `body` 선언이 그것을 가리므로 둘이
 * 싸우지 않는다. 사람마다 프로젝터가 다르니 그 창에서 바로 조절하는 편이 낫다.
 */

import type { Template } from '../shared/types.ts';

/** 바탕 프리셋 — '전체 — 성경·찬송 겸용' */
export const PROJECTOR_TEMPLATE_ID = -8;

/** WebSocket 에서 이 화면을 가리키는 이름 */
export const PROJECTOR_LAYER = 'projector';

/**
 * 프로젝터용으로 고친 사본을 돌려준다. 원본은 건드리지 않는다.
 *
 * 고치는 것은 **autoFit 하나뿐**이다.
 *
 * autoFit 은 글이 넘칠 때 화면에 맞게 줄여 주는 기능이다. 프로젝터에서는 이것이
 * `+` 버튼과 싸운다 — 키우면 넘치고, 넘치니 다시 줄여서, **글자 크기가 바뀌지 않는
 * 것처럼 보인다.** (2026-08-19 에 내가 오진한 현상이 정확히 이것이다.)
 * 조작자는 벽에 비친 글씨를 직접 보고 있으니, 넘치면 스스로 `−` 를 누르면 된다.
 * 넘치는 동안에는 화면 막대에 그 사실을 알린다.
 */
export function projectorTemplate(base: Template): Template {
  return {
    ...base,
    behavior: {
      ...base.behavior,
      // 1 = 줄이지 않는다. 값이 1 미만이면 조작자의 + 를 되돌려 깎는다
      autoFitMinScale: 1,
    },
  };
}
